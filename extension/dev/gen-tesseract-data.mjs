// Regenerates vendor/tesseract/tess-data.js from a locally obtained
// tesseract-core-lstm.wasm (tesseract.js-core npm package) and eng.traineddata
// (tesseract-ocr/tessdata, standard accuracy, not the "fast" variant), gzipped.
// Not shipped itself; rerun this after bumping the vendored tesseract version.
//
// Why this exists: the manifest's CSP is `connect-src 'none'`, which blocks
// ANY fetch()/XHR from extension pages and their workers, including to the
// extension's own chrome-extension:// resources (verified empirically: a
// fetch() to a blob:, data:, or same-origin URL under connect-src 'none' all
// fail the same way pdf.js's standard-font fetch does, see core/pdf.js's
// installStandardFontFetchShim). Tesseract.js's worker script and the
// emscripten-generated wasm glue both load their binary payloads (the core
// .wasm and the language traineddata) via a real fetch() call, so those
// calls would be blocked in the packaged extension. The only load path that
// isn't classified as a "connection" under CSP is a script load
// (importScripts/script-src), so the payloads are embedded as base64 in a
// plain script and injected via a self.fetch shim patched into worker.min.js
// (see the PATCH block there) instead of ever hitting the network stack.
import fs from 'node:fs';

const [, , wasmPath, traineddataGzPath] = process.argv;
if (!wasmPath || !traineddataGzPath) {
  console.error('usage: node gen-tesseract-data.mjs <tesseract-core-lstm.wasm> <eng.traineddata.gz>');
  process.exit(1);
}

const wasmB64 = fs.readFileSync(wasmPath).toString('base64');
const langB64 = fs.readFileSync(traineddataGzPath).toString('base64');

const out = `// Auto-generated by dev/gen-tesseract-data.mjs. Do not hand-edit.
// Base64 payloads for the Tesseract core wasm binary and the English
// traineddata (gzipped), injected into the Tesseract worker's self.fetch
// shim (see the PATCH block at the top of worker.min.js) so the emscripten
// core and language loaders never need a real network fetch, which the
// manifest's connect-src 'none' would block.
self.__SB_TESS_DATA__ = {
  wasm: ${JSON.stringify(wasmB64)},
  engTraineddataGz: ${JSON.stringify(langB64)},
};
`;
fs.writeFileSync(new URL('../vendor/tesseract/tess-data.js', import.meta.url), out);
console.log('wrote tess-data.js:', (out.length / 1e6).toFixed(1), 'MB (wasm', (wasmB64.length/1e6).toFixed(1), 'MB b64, lang', (langB64.length/1e6).toFixed(1), 'MB b64)');
