// Regenerates vendor/standard-fonts-data.js from vendor/standard_fonts/*.
// Run after updating vendor/pdf.min.mjs + pdf.worker.min.mjs to a new pdf.js
// version (fetch the matching pdfjs-dist tarball's standard_fonts/ folder
// into vendor/standard_fonts/ first, then run this). Not shipped itself.
import fs from 'node:fs';
import path from 'node:path';

const dir = new URL('../vendor/standard_fonts/', import.meta.url);
const files = fs.readdirSync(dir).filter((f) => !f.startsWith('LICENSE'));
const entries = files.map((f) => {
  const b64 = fs.readFileSync(new URL(f, dir)).toString('base64');
  return `  ${JSON.stringify(f)}: ${JSON.stringify(b64)}`;
});
const out = `// Auto-generated by dev/gen-standard-fonts-data.mjs from vendor/standard_fonts/*.
// Base64 of pdf.js's base-14 font substitutes (Foxit/Liberation, see
// vendor/standard_fonts/LICENSE_*), inlined so loadPdfPages can serve them to
// pdf.js without an actual network fetch (the manifest CSP is connect-src
// 'none', so a real fetch() to any URL, even a same-origin extension
// resource, is blocked).
export const STANDARD_FONTS_BASE64 = {
${entries.join(',\n')}
};
`;
fs.writeFileSync(new URL('../vendor/standard-fonts-data.js', import.meta.url), out);
console.log('wrote', out.length, 'bytes,', files.length, 'fonts');
